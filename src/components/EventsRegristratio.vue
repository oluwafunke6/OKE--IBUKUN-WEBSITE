 # A Heartfelt Welcome from the Pastor

**Grace and peace be unto you in the name of our Lord and Saviour, Jesus Christ.**

On behalf of the ministers, workers, and the entire family of **Christ Apostolic Church OKE-IBUKUN**, I warmly welcome you to our church and to our online home.

We are deeply grateful to God for leading you here. Whether you are visiting for the first time, searching for a place to worship, or returning to fellowship with us, know that you are loved, valued, and warmly received. It is our prayer that your visit will bring you closer to God and strengthen your faith in Jesus Christ.

At Christ Apostolic Church OKE-IBUKUN, we are committed to proclaiming the undiluted Word of God, nurturing believers through fervent prayer, heartfelt worship, sound biblical teaching, and compassionate service. Our desire is to see lives transformed, families restored, and communities impacted by the power of the Holy Spirit.

No matter where you are on your spiritual journey, there is a place for you here. We invite you to join us in our worship services, prayer meetings, Bible studies, and outreach programs as we grow together in the knowledge and grace of our Lord Jesus Christ.

As you explore our website, we pray you will find encouragement, inspiration, and opportunities to connect with our church family. May the Lord richly bless you, guide your steps, and fill your heart with His perfect peace.

We look forward to welcoming you personally to one of our services.

**May the grace of our Lord Jesus Christ, the love of God, and the fellowship of the Holy Spirit be with you always. Amen.**

With heartfelt gratitude and Christian love,

**Pastor S. O. Olaiya**
Lead Pastor
**Christ Apostolic Church OKE-IBUKUN**
